const ALIASES: Readonly<Record<string, string>> = {
    "❤": "♥",
    "♡": "♥",
    "☆": "★"
};

/** Emoji variation selectors and joiners carry no shape of their own. */
export function stripInvisible(text: string): string {
    return text.replace(/[︎️‍]/g, "");
}

/** Glyphs as boolean pixel rows. */
export const GLYPHS: ReadonlyMap<string, readonly (readonly boolean[])[]> = new Map(
    Object.entries(RAW_GLYPHS).map(([char, rows]) => [
        char,
        rows.map((row) => [...row].map((pixel) => pixel === "#"))
    ])
);

/** Normalizes a character to the key used in the font (uppercase, aliases). */
export function glyphKey(char: string): string {
    const alias = ALIASES[char];
    if (alias) return alias;
    return char.toUpperCase();
}

export function supportedCharacters(): string {
    return [...GLYPHS.keys()].filter((char) => char !== " ").join("");
}
